create table storage
(
    id                  bigserial primary key,
    name                varchar(500) not null,
    active              boolean default true,
    is_pharmacy_storage boolean default false
);

create table country
(
    id   bigint primary key,
    name varchar(500) not null
);

create table pharm_user
(
    id                bigserial primary key,
    username          varchar(500) unique not null,
    name              varchar(500),
    surname           varchar(500),
    lastname          varchar(500),
    active            boolean             default true,
    password          varchar(500)        not null,
    role              varchar(500)        not null,
    linked_storage_id bigint references storage (id)
);

create table product
(
    id                   bigserial primary key,
    type                 varchar(500) not null,
    name                 varchar(500) not null,
    active               boolean default true,
    description          text,
    image_id             bigint,
    is_required_recipe   boolean default false,
    manufacturer         varchar(500),
    country_of_origin_id bigint       not null
);

create table request
(
    id            bigserial primary key,
    creator_id    bigint references pharm_user (id),
    handler_id    bigint references pharm_user (id),
    creation_date timestamp not null
);

create table batch
(
    id                   bigserial primary key,
    count                int    not null default 0,
    total_reserved_count int    not null default 0,
    active               boolean         default true,
    product_id           bigint not null references product (id),
    storage_id           bigint not null references storage (id),
    manufacture_date     date   not null,
    expiration_date      date   not null
);

create table request_batch
(
    id              bigint primary key,
    count           int                    default 0,
    request_id      bigint references request (id) not null,
    source_batch_id bigint                      not null references batch (id),
    target_batch_id bigint                      not null references batch (id)
);

